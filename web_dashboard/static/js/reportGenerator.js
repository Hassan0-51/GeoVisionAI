/**
 * GeoAI — Professional PDF Report Generator
 * Generates a structured, branded PDF from the dashboard using jsPDF + html2canvas.
 */
async function generatePDF() {
    const { jsPDF } = window.jspdf;
    const btn = document.getElementById('export-btn');
    if (!btn) return;
    const originalHTML = btn.innerHTML;

    try {
        btn.disabled = true;
        btn.innerHTML = '<span class="spinner-border spinner-border-sm me-2"></span>Generating…';

        const pdf = new jsPDF('p', 'mm', 'a4');
        const PW = pdf.internal.pageSize.getWidth();   // 210
        const PH = pdf.internal.pageSize.getHeight();  // 297
        const ML = 18, MR = 18, MT = 15;
        const CW = PW - ML - MR;  // usable column width
        let y = 0;

        // ── Colour palette ──────────────────────────────────────────
        const C = {
            dark:     [15,  23, 42],
            primary:  [22, 101, 52],
            accent:   [16, 185, 129],
            muted:    [100, 116, 139],
            light:    [241, 245, 249],
            white:    [255, 255, 255],
            red:      [220, 38, 38],
            border:   [226, 232, 240],
        };

        // ── Helpers ─────────────────────────────────────────────────
        const setFont = (size, style='normal', color=C.dark) => {
            pdf.setFontSize(size);
            pdf.setFont('helvetica', style);
            pdf.setTextColor(...color);
        };
        const fillRect = (x, fy, w, h, color) => {
            pdf.setFillColor(...color);
            pdf.rect(x, fy, w, h, 'F');
        };
        const line = (x1, fy1, x2, fy2, color=C.border) => {
            pdf.setDrawColor(...color);
            pdf.setLineWidth(0.3);
            pdf.line(x1, fy1, x2, fy2);
        };
        const addPage = () => { pdf.addPage(); y = MT; };

        // Check remaining space; if tight add page
        const ensureSpace = (needed) => {
            if (y + needed > PH - 20) addPage();
        };

        // Render wrapped text; returns new y
        const writeWrapped = (text, x, fy, maxW, lineH=5.5) => {
            const lines = pdf.splitTextToSize(String(text), maxW);
            pdf.text(lines, x, fy);
            return fy + lines.length * lineH;
        };

        // ── COVER PAGE ───────────────────────────────────────────────
        // Dark background
        fillRect(0, 0, PW, PH, C.dark);

        // Green accent bar (left side)
        fillRect(0, 0, 6, PH, C.primary);

        // Accent stripe
        fillRect(6, 80, PW - 6, 2, C.accent);
        fillRect(6, 82, PW - 6, 0.5, [255,255,255]);

        // Logo circle
        pdf.setFillColor(...C.primary);
        pdf.circle(ML + 14, 45, 14, 'F');
        setFont(20, 'bold', C.white);
        pdf.text('G', ML + 11, 50);

        // Title block
        setFont(26, 'bold', C.white);
        pdf.text('GeoAI Analysis Report', ML + 32, 42);
        setFont(11, 'normal', [148, 163, 184]);
        pdf.text('Urban Land Cover & Environmental Intelligence Platform', ML + 32, 50);

        // Divider after stripe
        y = 95;
        setFont(9, 'normal', [100, 116, 139]);
        pdf.text('GENERATED BY GEOAI PLATFORM', ML, y);
        pdf.text(new Date().toLocaleString(), PW - MR, y, { align: 'right' });

        y += 8;
        if (typeof RESULT_ID !== 'undefined' && RESULT_ID) {
            setFont(9, 'normal', [148, 163, 184]);
            pdf.text(`Analysis Reference: ${RESULT_ID}`, ML, y);
            y += 6;
        }

        // Meta cards
        const metaCards = [
            { label: 'ANALYSIS AREA', value: 'Lahore Metropolitan Region' },
            { label: 'COORDINATE SYSTEM', value: 'WGS 84 / EPSG:4326' },
            { label: 'DATA SOURCE', value: 'Satellite Imagery (Sentinel / Landsat)' },
            { label: 'REPORT DATE', value: new Date().toLocaleDateString('en-GB', { year:'numeric', month:'long', day:'numeric' }) },
        ];

        y += 6;
        const cardW = (CW - 10) / 2;
        metaCards.forEach((card, i) => {
            const cx = ML + (i % 2) * (cardW + 10);
            const cy = y + Math.floor(i / 2) * 28;
            fillRect(cx, cy, cardW, 22, [30, 41, 59]);
            setFont(7, 'bold', C.accent);
            pdf.text(card.label, cx + 5, cy + 8);
            setFont(9, 'normal', C.white);
            const wrapped = pdf.splitTextToSize(card.value, cardW - 10);
            pdf.text(wrapped, cx + 5, cy + 15);
        });

        y += 70;

        // Confidentiality notice
        setFont(8, 'italic', [71, 85, 105]);
        pdf.text('This report is generated for research and educational purposes. All data is processed locally.', ML, y, { maxWidth: CW });

        // ── PAGE 2: EXECUTIVE SUMMARY ────────────────────────────────
        addPage();

        // Section header helper
        const sectionHeader = (title, icon='') => {
            ensureSpace(18);
            fillRect(ML, y, CW, 10, C.primary);
            setFont(11, 'bold', C.white);
            pdf.text(title, ML + 4, y + 7);
            y += 16;
        };

        // Page header strip (reused on each page from p2 onwards)
        const pageHeader = () => {
            fillRect(0, 0, PW, 12, C.dark);
            setFont(8, 'bold', C.white);
            pdf.text('GeoAI Land Cover Analysis Report', ML, 8);
            pdf.text(new Date().toLocaleDateString(), PW - MR, 8, { align: 'right' });
            y = 18;
        };

        pageHeader();
        sectionHeader('01. Executive Summary');

        // Pull LLM insights text from the DOM
        const summaryEl = document.getElementById('json-viewer');
        if (summaryEl && summaryEl.textContent.trim()) {
            const rawSummary = summaryEl.textContent.trim().substring(0, 800);
            setFont(9, 'normal', C.dark);
            y = writeWrapped(rawSummary, ML, y, CW, 5.5) + 4;
        } else {
            setFont(9, 'italic', C.muted);
            pdf.text('No AI-generated insights available for this analysis run.', ML, y);
            y += 10;
        }

        // Key metrics row
        const totalCarbon = document.getElementById('total-carbon')?.textContent?.trim() || '—';
        const greenRatio  = document.querySelector('[id*="green"]')?.textContent?.trim() || '—';

        const kpis = [
            { label: 'Carbon Sequestration', value: totalCarbon, unit: 'tons' },
            { label: 'Analysis Mode', value: (typeof DEFAULT_SEASON !== 'undefined' ? DEFAULT_SEASON.toUpperCase() : 'N/A'), unit: '' },
            { label: 'Report Year', value: (typeof DEFAULT_YEAR !== 'undefined' ? DEFAULT_YEAR : new Date().getFullYear()), unit: '' },
        ];

        ensureSpace(30);
        const kpiW = CW / kpis.length;
        kpis.forEach((kpi, i) => {
            const kx = ML + i * kpiW;
            fillRect(kx, y, kpiW - 3, 24, C.light);
            setFont(7, 'bold', C.muted);
            pdf.text(kpi.label.toUpperCase(), kx + 4, y + 7);
            setFont(13, 'bold', C.primary);
            pdf.text(String(kpi.value), kx + 4, y + 17);
            if (kpi.unit) {
                setFont(7, 'normal', C.muted);
                pdf.text(kpi.unit, kx + 4 + pdf.getTextWidth(String(kpi.value)) + 2, y + 17);
            }
        });
        y += 30;

        // ── SECTION: MAP SNAPSHOT ─────────────────────────────────────
        sectionHeader('02. Region of Interest — Map View');

        const mapEl = document.getElementById('map');
        if (mapEl) {
            try {
                const mapCanvas = await html2canvas(mapEl, { useCORS: true, allowTaint: true, logging: false, scale: 1.5 });
                const mapImg = mapCanvas.toDataURL('image/jpeg', 0.85);
                const mapH = CW * (mapCanvas.height / mapCanvas.width);
                ensureSpace(mapH + 6);
                pdf.addImage(mapImg, 'JPEG', ML, y, CW, mapH);
                // Legend caption
                y += mapH + 3;
                setFont(7.5, 'italic', C.muted);
                pdf.text('Figure 1: Interactive land cover classification map overlaid on satellite imagery.', ML, y);
                y += 8;
            } catch (e) {
                setFont(9, 'italic', C.muted);
                pdf.text('[Map snapshot unavailable — cross-origin tile restriction]', ML, y);
                y += 10;
            }
        }

        // ── SECTION: LAND COVER CLASSIFICATION TABLE ─────────────────
        ensureSpace(60);
        sectionHeader('03. Land Cover Classification');

        // Class legend table
        const classes = [
            { name: 'Urban / Built-up',      color: [255, 0, 0],     desc: 'Roads, buildings, impervious surfaces' },
            { name: 'Trees / Forest',         color: [0, 128, 0],     desc: 'Dense tree cover, woodland, forest patches' },
            { name: 'Water Bodies',           color: [0, 0, 255],     desc: 'Rivers, canals, reservoirs, wetlands' },
            { name: 'Agricultural Land',      color: [60, 176, 67],   desc: 'Cropland, irrigated fields, farms' },
            { name: 'Bare Soil / Wasteland',  color: [139, 69, 19],   desc: 'Exposed soil, construction sites, barren land' },
            { name: 'Grass & Shrubland',      color: [255, 255, 0],   desc: 'Grasslands, shrubs, low vegetation' },
        ];

        // Table header
        const colWidths = [6, 55, CW - 61];
        const rowH = 9;
        let tx = ML;
        fillRect(tx, y, CW, rowH, C.dark);
        setFont(8, 'bold', C.white);
        pdf.text('', tx + 2, y + 6);
        pdf.text('Class Name', tx + 10, y + 6);
        pdf.text('Description', tx + colWidths[0] + colWidths[1] + 2, y + 6);
        y += rowH;

        classes.forEach((cls, i) => {
            ensureSpace(rowH + 1);
            fillRect(ML, y, CW, rowH, i % 2 === 0 ? C.white : C.light);
            // Swatch
            pdf.setFillColor(...cls.color);
            pdf.roundedRect(ML + 1, y + 2, 5, 5, 1, 1, 'F');
            setFont(8.5, 'normal', C.dark);
            pdf.text(cls.name, ML + 10, y + 6.5);
            setFont(8, 'normal', C.muted);
            pdf.text(cls.desc, ML + colWidths[0] + colWidths[1] + 2, y + 6.5);
            // Row border
            line(ML, y + rowH, ML + CW, y + rowH, C.border);
            y += rowH;
        });
        y += 6;

        // ── SECTION: DATA VISUALIZATIONS ─────────────────────────────
        addPage();
        pageHeader();
        sectionHeader('04. Data Visualizations');

        // Capture all visible chart containers
        const chartContainers = document.querySelectorAll('.tab-pane');
        let figNum = 2;
        for (const container of chartContainers) {
            if (container.querySelector('[id^="plot-"]')) {
                try {
                    const chartCanvas = await html2canvas(container, { scale: 1.5, useCORS: true, logging: false, backgroundColor: '#ffffff' });
                    const chartImg = chartCanvas.toDataURL('image/jpeg', 0.9);
                    const chartH = Math.min(CW * (chartCanvas.height / chartCanvas.width), 100);
                    ensureSpace(chartH + 10);
                    pdf.addImage(chartImg, 'JPEG', ML, y, CW, chartH);
                    y += chartH + 3;
                    setFont(7.5, 'italic', C.muted);
                    pdf.text(`Figure ${figNum++}: Land cover and temperature trend visualizations.`, ML, y);
                    y += 8;
                } catch (e) {
                    // Skip if chart render fails
                }
            }
        }

        // ── SECTION: ADVANCED METRICS ─────────────────────────────────
        const advContainer = document.querySelector('.advanced-analysis-container');
        if (advContainer) {
            ensureSpace(20);
            sectionHeader('05. Advanced Metrics & Environmental Analysis');
            try {
                const origOverflow = advContainer.style.overflow;
                advContainer.style.overflow = 'visible';
                const advCanvas = await html2canvas(advContainer, { scale: 1.5, useCORS: true, logging: false, backgroundColor: '#ffffff' });
                advContainer.style.overflow = origOverflow;
                const advImg = advCanvas.toDataURL('image/jpeg', 0.9);
                const advH = Math.min(CW * (advCanvas.height / advCanvas.width), 120);
                ensureSpace(advH + 8);
                pdf.addImage(advImg, 'JPEG', ML, y, CW, advH);
                y += advH + 4;
                setFont(7.5, 'italic', C.muted);
                pdf.text(`Figure ${figNum}: Advanced metrics including NDVI, carbon sequestration, and environmental indices.`, ML, y, { maxWidth: CW });
                y += 10;
            } catch(e) { /* skip */ }
        }

        // ── SECTION: METHODOLOGY & DISCLAIMER ────────────────────────
        ensureSpace(60);
        sectionHeader('06. Methodology & Data Sources');

        const methodText = [
            'This analysis was performed using a deep learning land cover classification model trained on multi-spectral satellite imagery. ' +
            'The model segments each pixel into one of six land cover classes: Urban, Trees, Water, Agriculture, Soil, and Grass.',
            '',
            'Imagery Sources: Sentinel-2 MSI (10 m) and Landsat-8/9 OLI (30 m) | Temperature: MODIS MOD11A2 LST product.',
            '',
            'Results are generated via automated image processing pipelines. Values represent percentage cover within the defined Region of Interest (ROI). ' +
            'Minor positional errors (±30 m) may exist due to sensor resolution limitations.',
        ];

        setFont(9, 'normal', C.dark);
        methodText.forEach(para => {
            if (para === '') { y += 3; return; }
            y = writeWrapped(para, ML, y, CW, 5.5) + 2;
        });

        // Disclaimer box
        ensureSpace(20);
        y += 4;
        fillRect(ML, y, CW, 18, [254, 249, 195]);
        pdf.setDrawColor(234, 179, 8);
        pdf.setLineWidth(0.5);
        pdf.rect(ML, y, CW, 18, 'S');
        setFont(8, 'bold', [133, 77, 14]);
        pdf.text('⚠  Disclaimer', ML + 4, y + 6);
        setFont(7.5, 'normal', [92, 64, 20]);
        pdf.text('Results are intended for research and educational purposes only. Verify critical decisions with field surveys.', ML + 4, y + 12, { maxWidth: CW - 8 });
        y += 22;

        // ── FOOTER on every page ─────────────────────────────────────
        const totalPages = pdf.internal.getNumberOfPages();
        for (let p = 1; p <= totalPages; p++) {
            pdf.setPage(p);
            // Bottom bar
            fillRect(0, PH - 12, PW, 12, C.dark);
            setFont(7.5, 'normal', [148, 163, 184]);
            pdf.text('GeoAI Urban Land Cover Analysis Platform  ·  Confidential', ML, PH - 5);
            setFont(7.5, 'bold', C.white);
            pdf.text(`Page ${p} of ${totalPages}`, PW - MR, PH - 5, { align: 'right' });
            // Green left accent on all pages
            fillRect(0, 0, 3, PH, C.primary);
        }

        // ── SAVE ─────────────────────────────────────────────────────
        const dateStr = new Date().toISOString().slice(0, 10);
        pdf.save(`GeoAI_Report_${dateStr}.pdf`);

    } catch (err) {
        console.error('PDF Generation Error:', err);
        alert('Failed to generate PDF report. See browser console for details.');
    } finally {
        btn.innerHTML = originalHTML;
        btn.disabled = false;
    }
}
